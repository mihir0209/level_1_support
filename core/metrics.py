"""
Prometheus metrics registry for Level 1 Support Automation.
Tracks message counts, session outcomes, latencies, and token usage, partitioned by brand_id.
"""

from __future__ import annotations

from prometheus_client import Counter, Histogram

# ── General Message & Session Metrics ────────────────────────────────────────

MESSAGES_TOTAL = Counter(
    "l1_messages_total",
    "Total messages processed",
    ["brand_id", "channel"]
)

RESOLUTION_LATENCY = Histogram(
    "l1_resolution_latency_seconds",
    "End-to-end latency per turn",
    ["brand_id"]
)

ESCALATION_TOTAL = Counter(
    "l1_escalations_total",
    "Total escalations",
    ["brand_id", "reason"]
)

SESSIONS_TOTAL = Counter(
    "l1_sessions_total",
    "Total sessions created",
    ["brand_id", "channel"]
)

# ── Multi-Tenant Token Usage Metrics (Billing / Cost Control) ───────────────

TOKEN_USAGE_INPUT = Counter(
    "l1_token_usage_input_total",
    "Total input/prompt tokens consumed by LLM completion calls",
    ["brand_id"]
)

TOKEN_USAGE_OUTPUT = Counter(
    "l1_token_usage_output_total",
    "Total output/completion tokens generated by LLM completion calls",
    ["brand_id"]
)


# ── HITL Action Approval Metrics ──────────────────────────────────────────────

APPROVAL_REQUESTS_TOTAL = Counter(
    "l1_approval_requests_total",
    "Total human approval actions requested",
    ["brand_id", "tool_name"]
)

APPROVAL_DECISIONS_TOTAL = Counter(
    "l1_approval_decisions_total",
    "Total human decisions for action approvals",
    ["brand_id", "tool_name", "decision"]
)

APPROVAL_LATENCY_SECONDS = Histogram(
    "l1_approval_latency_seconds",
    "Latency/duration from action pause to supervisor review decision",
    ["brand_id", "tool_name", "decision"]
)
